// Development-only: use the same pinned font reader already used by pdfmake.
import { createRequire } from 'node:module';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
const require = createRequire(import.meta.url);
const fontkit = createRequire(require.resolve('pdfmake/package.json'))('@foliojs-fork/fontkit');
import { fontFiles } from '../app/pdf/fonts.js';
const hashes = {};
let supported;
for (const file of fontFiles) {
  const bytes = await readFile(new URL(`../assets/fonts/${file}`, import.meta.url));
  const font = fontkit.create(bytes);
  const codes = font.characterSet.filter(code => font.hasGlyphForCodePoint(code));
  supported = supported ? supported.filter(code => codes.includes(code)) : codes;
  hashes[file] = createHash('sha256').update(bytes).digest('hex');
}
const ranges = [];
for (const code of supported.sort((a, b) => a - b)) {
  const last = ranges.at(-1);
  if (last && last[1] === code - 1) last[1] = code;
  else ranges.push([code, code]);
}
await writeFile(new URL('../app/pdf/font-coverage.js', import.meta.url), `// Generated by node scripts/font-coverage.mjs from the bundled fonts. Do not edit.\nexport const fontHashes = ${JSON.stringify(hashes, null, 2)};\nexport const supportedRanges = ${JSON.stringify(ranges)};\n`);
